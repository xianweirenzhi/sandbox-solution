#pragma once

// SoilSensor：土壤湿度采集（模拟量，AO 口 → 开发板唯一 ADC 引脚 A0）。
// 仅采集滤波原始值，不做湿/干判定——判定与阈值已上移主机（esp32-2 的
// auto_ctrl 按端口配置、网页可调）；本模块负责提供稳定的上报/上屏原始值。
// 数值语义：AO 电压低 = 土壤湿润适宜，AO 电压高 = 偏干（低=湿 高=干）。
// 对外提供两级数值：滤波原始值 getRaw()（0~1023）与百分比 getPct()（0~100，
// 按分压满量程折算，上传主机/上屏用百分比）。
// 接线：模块 VCC→开发板 3V3，GND→GND，AO→[分压]→A0（DO 悬空）。
//       ★模块 AO 满摆幅约 3.3V，而 HUZZAH ADC 量程仅 0~1V——必须经分压
//         （现场采用 3×1kΩ 串联 + 1kΩ 的 4:1 链，3.3V→0.825V）再入 A0，
//         直连超量程会读数贴顶并可能损伤 ADC。
// 说明：模拟器件无“在线探测”概念（AO 拔线后 A0 悬空读数不可信，表现类似贴顶）。
//       实现细节收敛在 .cpp（pimpl），头文件不依赖 Arduino / 库。

class SoilSensor {
 public:
  SoilSensor();
  ~SoilSensor();

  // 初始化 ADC 并完成首采（首个原始值立即可用，供上报/上屏）
  bool begin();

  // 周期维护：中值滤波采集 + 贴顶提醒
  void handle();

  // 最近一次滤波后原始 ADC 值（0~1023，对应 A0 0~1.0V；标定/排障用）
  int getRaw() const;

  // 湿度读数百分比 0~100（= raw×100/满量程，低=湿 高=干；上报主机/上屏用。
  // 湿/干阈值判定在主机侧，本机不再给出两态结论）
  uint8_t getPct() const;

 private:
  struct Impl;  // 实现体（定义在 .cpp）
  Impl *_p;
};
